// Helper to get domain icon
export function getDomainIcon(domainId, props = {}) {
  switch (domainId) {
    case 'school':   return <SchoolIcon {...props} />
    case 'identity': return <IdentityIcon {...props} />
    case 'personal': return <PersonalIcon {...props} />
    case 'vehicle':  return <VehicleIcon {...props} />
    case 'health':   return <HealthIcon {...props} />
    case 'banking':  return <BankingIcon {...props} />
    case 'college':  return <CollegeIcon {...props} />
    default:         return <DocumentPageIcon {...props} />
  }
}

// Helper to get document type icon based on document metadata
export function getDocumentIcon(doc, props = {}) {
  if (doc.status === 'empty') {
    return <EmptyDocIcon {...props} />
  }
  if (doc.type === 'text') {
    return <TextValueIcon {...props} />
  }
  const title = (doc.title || '').toLowerCase()
  const mime = (doc.mimeType || '').toLowerCase()

  if (title.includes('qr') || title.includes('pay') || title.includes('upi')) {
    return <QrCodeIcon {...props} />
  }
  if (title.includes('signature') || title.includes('sign')) {
    return <SignatureIcon {...props} />
  }
  if (title.includes('aadhar') || title.includes('pan') || title.includes('voter') || title.includes('passport') || title.includes('license')) {
    return <IdentityIcon {...props} />
  }
  if (title.includes('marksheet') || title.includes('certificate') || title.includes('domicile') || title.includes('degree')) {
    return <CertificateIcon {...props} />
  }
  if (title.includes('rc') || title.includes('vehicle') || title.includes('insurance') || title.includes('puc')) {
    return <VehicleIcon {...props} />
  }
  if (title.includes('bank') || title.includes('cheque') || title.includes('statement') || title.includes('passbook')) {
    return <BankingIcon {...props} />
  }
  if (mime.includes('image')) {
    return <ImageIcon {...props} />
  }
  return <DocumentPageIcon {...props} />
}

